import fs from 'node:fs/promises'
import path from 'node:path'
import {createHash} from 'node:crypto'
import {execFile} from 'node:child_process'
import {promisify} from 'node:util'
if(process.platform!=='darwin')process.exit(0)
const run=promisify(execFile), root=process.cwd(), dir=path.join(root,'build/macos-runtime')
await fs.mkdir(dir,{recursive:true})
const sources=['src/main/platform/macos-owned-memory.c','src/main/work-mode/macos-video.swift','scripts/build-macos-runtime.mjs']
const hash=b=>createHash('sha256').update(b).digest('hex')
const sourceDigest=hash(Buffer.concat(await Promise.all(sources.map(p=>fs.readFile(p)))))
await run('/usr/bin/xcrun',['clang','-O2','src/main/platform/macos-owned-memory.c','-o',path.join(dir,'owned-memory')],{timeout:30000,maxBuffer:16384})
await run('/usr/bin/xcrun',['swiftc','-O','src/main/work-mode/macos-video.swift','-o',path.join(dir,'video')],{timeout:60000,maxBuffer:32768})
const files={}
for(const name of ['owned-memory','video'])files[name]=hash(await fs.readFile(path.join(dir,name)))
await fs.writeFile('src/main/platform/macos-runtime-identity.generated.ts','// Generated by scripts/build-macos-runtime.mjs, never hand filled.\nexport const MACOS_RUNTIME_IDENTITY = '+JSON.stringify({platform:'darwin',arch:process.arch,sourceDigest,files},null,2)+' as const\n')
console.log(JSON.stringify({sourceDigest,files}))
