import fs from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'

if (process.platform !== 'darwin') process.exit(0)
const root = process.cwd()
const output = path.join(root, 'build/shelf-candidates')
await fs.mkdir(output, { recursive: true })
const sources = ['native/shelf-candidates/Shelf.swift', 'native/shelf-candidates/NativeWorkShelf.swift', 'native/shelf-candidates/WorkShelfInteraction.swift', 'native/shelf-candidates/WorkShelfPresentation.swift', 'native/shelf-candidates/WorkShelfColorPicker.swift', 'native/shelf-candidates/WorkShelfCapsule.swift', 'native/shelf-candidates/WorkShelfSystemActions.swift', 'native/shelf-candidates/WorkShelfOCR.swift', 'native/shelf-candidates/WorkShelfRedaction.swift', 'native/shelf-candidates/main.swift', 'scripts/build-shelf-candidates.mjs']
const hash = value => createHash('sha256').update(value).digest('hex')
const sourceDigest = hash(Buffer.concat(await Promise.all(sources.map(file => fs.readFile(file)))))
const app = path.join(output, 'DAM Shelf A.app')
await fs.mkdir(path.join(app, 'Contents/MacOS'), { recursive: true })
const binary = path.join(app, 'Contents/MacOS/Shelf')
await promisify(execFile)('/usr/bin/xcrun', ['swiftc', '-O', '-swift-version', '5', '-target', `${process.arch === 'arm64' ? 'arm64' : 'x86_64'}-apple-macosx13.0`, ...sources.filter(file => file.endsWith('.swift')),
  '-framework', 'AppKit', '-framework', 'QuartzCore', '-framework', 'QuickLookUI', '-framework', 'QuickLookThumbnailing', '-o', binary], { timeout: 120000, maxBuffer: 65536 })
await fs.writeFile(path.join(app, 'Contents/Info.plist'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleExecutable</key><string>Shelf</string>
<key>CFBundleIdentifier</key><string>com.dam.candidate.shelf-a</string>
<key>CFBundleName</key><string>DAM Shelf A</string>
<key>CFBundleVersion</key><string>1</string>
<key>CFBundleShortVersionString</key><string>0.1.0</string>
<key>LSUIElement</key><true/>
<key>NSHighResolutionCapable</key><true/>
<key>LSMinimumSystemVersion</key><string>13.0</string>
</dict></plist>`)
await promisify(execFile)('/usr/bin/codesign', ['--force', '--sign', '-', app], { timeout: 30000 })
const helperApp = path.join(output, 'DAM Shelf B.app')
await fs.mkdir(path.join(helperApp, 'Contents/MacOS'), { recursive: true })
const helperBinary = path.join(helperApp, 'Contents/MacOS/Shelf')
await fs.copyFile(binary, helperBinary)
await fs.writeFile(path.join(helperApp, 'Contents/Info.plist'),
  (await fs.readFile(path.join(app, 'Contents/Info.plist'), 'utf8')).replaceAll('com.dam.candidate.shelf-a', 'com.dam.candidate.shelf-b').replaceAll('DAM Shelf A', 'DAM Shelf B'))
await promisify(execFile)('/usr/bin/codesign', ['--force', '--sign', '-', helperApp], { timeout: 30000 })
const identity = { platform: process.platform, arch: process.arch, sourceDigest, binaryDigest: hash(await fs.readFile(helperBinary)),
  aBinaryDigest: hash(await fs.readFile(binary)), app, helperApp }
await fs.writeFile(path.join(output, 'identity.json'), JSON.stringify(identity, null, 2))
await fs.writeFile(path.join(root, 'src/main/work-mode/shelf-candidate-identity.generated.ts'),
  '// Generated by build-shelf-candidates.mjs.\nexport const SHELF_CANDIDATE_IDENTITY = ' +
  JSON.stringify({ platform: identity.platform, arch: identity.arch, sourceDigest, binaryDigest: identity.binaryDigest }, null, 2) + ' as const\n')
console.log(JSON.stringify(identity))
